def _score_lead(score: int) -> str:
    if score >= 85:
        return "The available evidence supports a mature and repeatable pattern in this area."
    if score >= 70:
        return "The available evidence supports a generally strong pattern with some room for clearer documentation."
    if score >= 50:
        return "The relevant pattern is visible, but it is not yet documented or applied consistently."
    if score >= 40:
        return "The available evidence is limited, and the relationship between the recorded process and output is not consistently traceable."
    if score >= 20:
        return "The record is weak in this area, so positive capability cannot be confirmed from the available evidence."
    return "The available record is insufficient to support a positive capability judgment in this area."


def _evidence_scope(analysis_data: Dict[str, Any]) -> str:
    source_context = analysis_data.get("source_context", {}) if isinstance(analysis_data, dict) else {}
    if not isinstance(source_context, dict):
        source_context = {}
    has_log = bool(
        analysis_data.get("log_text")
        or analysis_data.get("log")
        or source_context.get("has_log_text")
    )
    has_output = bool(
        analysis_data.get("output_text")
        or analysis_data.get("output")
        or source_context.get("has_output_text")
        or source_context.get("artifact_url")
        or source_context.get("screenshot_count")
    )
    if has_log and has_output:
        return "Both process evidence and output evidence are available for comparison."
    if has_log:
        return "The process can be reviewed from the available chat evidence, while direct output comparison is limited."
    if has_output:
        return "The output can be reviewed directly, while the recorded process evidence is limited."
    return "The assessment is limited to the analysis data available in this session."


def _axis_container(data: Dict[str, Any], container_key: str, aliases: Sequence[str]) -> Any:
    container = data.get(container_key, {}) if isinstance(data, dict) else {}
    if not isinstance(container, dict):
        return None
    for alias in aliases:
        if alias in container:
            return container.get(alias)
    return None


def _axis_custom_text(
    report_data: Dict[str, Any],
    analysis_data: Dict[str, Any],
    axis_id: str,
    aliases: Sequence[str],
    kind: str,
) -> str:
    key_sets = {
        "evaluation": ("evaluation", "assessment", "analysis"),
        "relationship": (
            "relationship_to_output",
            "output_relationship",
            "relationship",
            "causal_relationship",
            "relation",
        ),
        "conclusion": ("conclusion", "finding", "summary"),
    }
    keys = key_sets[kind]
    candidates: List[Any] = []
    for source, container_name in (
        (report_data, "axis_comment_blocks"),
        (report_data, "axis_details"),
        (analysis_data, "axis_details"),
    ):
        block = _axis_container(source, container_name, aliases)
        if isinstance(block, dict):
            candidates.extend(block.get(key) for key in keys)
        elif kind == "evaluation":
            candidates.append(block)

    candidates.extend(report_data.get(f"{axis_id}_{key}") for key in keys)
    candidates.extend(analysis_data.get(f"{axis_id}_{key}") for key in keys)
    if kind == "evaluation":
        candidates.append(_axis_container(report_data, "axis_comments", aliases))
        candidates.append(_axis_container(analysis_data, "axis_comments", aliases))
    return _first_english(*candidates)


def _axis_parts(
    report_data: Dict[str, Any],
    analysis_data: Dict[str, Any],
    axis_id: str,
    aliases: Sequence[str],
    score: int,
) -> Dict[str, str]:
    fallback = AXIS_FALLBACKS[axis_id]
    label = next((item[1] for item in (OVERALL_AXIS,) + tuple(AXES) if item[0] == axis_id), axis_id)
    improvement_note = AXIS_IMPROVEMENT_NOTES[axis_id]
    if score < 50:
        evaluation = (
            f"{_score_lead(score)} The current material does not show enough consistent evidence to confirm "
            f"{label.lower()} as a reliable part of the user's AI workflow."
        )
        relationship = (
            "The available record does not establish a reliable correspondence between instructions or revisions "
            "and specific elements of the final output. The few visible similarities cannot be assigned confidently "
            "to a documented human decision."
        )
        conclusion = (
            f"This area remains difficult to evaluate as practical AI usage. More documentation is needed. "
            f"{improvement_note}"
        )
    else:
        evaluation = _axis_custom_text(report_data, analysis_data, axis_id, aliases, "evaluation")
        relationship = _axis_custom_text(report_data, analysis_data, axis_id, aliases, "relationship")
        conclusion = _axis_custom_text(report_data, analysis_data, axis_id, aliases, "conclusion")
        evaluation = evaluation or f"{_score_lead(score)} {fallback['evaluation']}"
        relationship = relationship or fallback["relationship"]
        conclusion = conclusion or fallback["conclusion"]
        improvement_markers = ("improv", "should", "need", "clearer", "would make", "room", "limit")
        if not any(marker in conclusion.lower() for marker in improvement_markers):
            conclusion = f"{conclusion} Improvement focus: {improvement_note}"
    return {
        "evaluation": _limit_text(evaluation, 760),
        "relationship": _limit_text(relationship, 720),
        "conclusion": _limit_text(conclusion, 620),
    }


