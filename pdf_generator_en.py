def _canonical_section_header(
    number: str,
    title: str,
    styles: Dict[str, ParagraphStyle],
    *,
    continued: bool = False,
    continued_label: str = "Continued",
    minimum_lines: int = 1,
) -> List[Any]:
    display_title = f"{title} — {continued_label}" if continued else title
    heading = Paragraph(
        _paragraph_text(f"{number}. {display_title}"),
        styles["section"],
    )
    _heading_width, heading_height = heading.wrap(CANONICAL_CONTENT_WIDTH, 100000)
    reserved_height = max(
        0.0,
        (max(1, int(minimum_lines)) * float(styles["section"].leading))
        - float(heading_height),
    )
    rule = Table([[""]], colWidths=[CANONICAL_CONTENT_WIDTH], rowHeights=[0.5 * mm])
    rule.setStyle(TableStyle([("LINEBELOW", (0, 0), (-1, -1), 1, GOLD)]))
    header: List[Any] = [
        Spacer(1, 4 * mm),
        heading,
    ]
    if reserved_height:
        header.append(Spacer(1, reserved_height))
    header.extend([rule, Spacer(1, 7 * mm)])
    return header


def _canonical_payload_rows(text: str, styles: Dict[str, ParagraphStyle]) -> List[List[Any]]:
    rows: List[List[Any]] = []
    for line in str(text or "").replace("\r\n", "\n").replace("\r", "\n").split("\n"):
        if line.startswith(("•", "・")):
            style = styles["bullet_body"]
        elif line[:3] in {"1. ", "2. ", "3. "} or re.match(r"^[①②③]", line):
            style = styles["subhead"]
        else:
            style = styles["body"]
        rows.append([Paragraph(_paragraph_text(line), style)])
    return rows


