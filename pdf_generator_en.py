    canvas.rect(0, 0, width, height, fill=1, stroke=0)
    canvas.setFillColor(GOLD)
    canvas.rect(14 * mm, 18 * mm, 1.6 * mm, height - 36 * mm, fill=1, stroke=0)
    canvas.setStrokeColor(LINE)
    canvas.setLineWidth(0.6)
    canvas.line(22 * mm, height - 15 * mm, width - 18 * mm, height - 15 * mm)
    canvas.line(22 * mm, 14 * mm, width - 18 * mm, 14 * mm)
    canvas.setFillColor(GOLD)
    canvas.setFont("Helvetica", 8)
    canvas.drawString(22 * mm, height - 11.2 * mm, REPORT_TITLE)
    canvas.setFillColor(MUTED)
