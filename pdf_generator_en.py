def _clean_text(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, dict):
        value = "\n".join(_clean_text(item) for item in value.values())
    elif isinstance(value, (list, tuple, set)):
        value = "\n".join(_clean_text(item) for item in value)
    text = CONTROL_CHAR_RE.sub(" ", str(value))
    text = re.sub(r"[ \t]+", " ", text)
    text = re.sub(r"\s*\n\s*", "\n", text)
    return text.strip()


def _english_text(value: Any) -> str:
    text = _clean_text(value)
    if not text or JAPANESE_TEXT_RE.search(text):
        return ""
    if not re.search(r"[A-Za-z]", text):
        return ""
    return text


def _first_english(*values: Any) -> str:
    for value in values:
        text = _english_text(value)
        if text:
            return text
    return ""


def _first_nonempty_text(*values: Any) -> str:
    """Return the first scalar value without applying language filtering."""
    for value in values:
        if value is None or isinstance(value, (dict, list, tuple, set)):
            continue
        text = str(value).strip()
        if text:
            return text
    return ""


def _limit_text(text: str, max_chars: int) -> str:
    text = _clean_text(text)
    if len(text) <= max_chars:
        return text
    shortened = text[: max_chars - 3].rstrip()
    sentence_end = max(shortened.rfind(". "), shortened.rfind("? "), shortened.rfind("! "))
    if sentence_end >= int(max_chars * 0.55):
        return shortened[: sentence_end + 1]
    word_end = shortened.rfind(" ")
    if word_end > 0:
        shortened = shortened[:word_end]
    return shortened.rstrip(" ,;:") + "..."


def _paragraph_text(value: Any) -> str:
    return escape(_clean_text(value)).replace("\n", "<br/>")


def _coerce_score(value: Any) -> int:
    try:
        score = int(float(value))
    except (TypeError, ValueError):
        score = 0
    return max(0, min(100, score))


def _extract_scores(analysis_data: Dict[str, Any]) -> Dict[str, int]:
    raw = analysis_data.get("scores", {}) if isinstance(analysis_data, dict) else {}
    if not isinstance(raw, dict):
        raw = {}
    scores: Dict[str, int] = {}
    for axis_id, _label, aliases in AXES:
        value: Any = 0
        for alias in aliases:
            if alias in raw:
                value = raw.get(alias)
                break
        scores[axis_id] = _coerce_score(value)
    return scores


def _total_score(analysis_data: Dict[str, Any], scores: Dict[str, int]) -> int:
    try:
        total = int(float(analysis_data.get("total_score", 0)))
    except (AttributeError, TypeError, ValueError):
        total = 0
    if total <= 0:
        total = sum(scores.values())
    return max(0, min(500, total))


def _canonical_json(value: Any) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))


def _normalize_digest_value(value: Any) -> Any:
    """Make the complete PDF source data deterministic before hashing."""
    if isinstance(value, dict):
        return {str(key): _normalize_digest_value(child) for key, child in value.items()}
    if isinstance(value, (list, tuple)):
        return [_normalize_digest_value(child) for child in value]
    if isinstance(value, set):
        normalized = [_normalize_digest_value(child) for child in value]
        return sorted(normalized, key=_canonical_json)
    if isinstance(value, (str, int, float, bool)) or value is None:
        return value
    return str(value)


def _extract_pdf_digest_text(pdf_bytes: bytes) -> List[str]:
    """Extract stable page text that can be rebuilt from the delivered PDF."""
    pages = PdfReader(BytesIO(pdf_bytes)).pages
    descriptions = {
        " ".join(QR_DESCRIPTION_EN.split()),
        " ".join(QR_DESCRIPTION_JA.split()),
    }
    normalized_pages: List[str] = []
    for page in pages:
        text = _clean_text(page.extract_text() or "")
        text = " ".join(text.split())
        # The description is added after the digest is calculated. Remove it
        # so the final PDF and the pre-QR PDF produce the same digest.
        for description in descriptions:
            text = text.replace(description, "")
        normalized_pages.append(" ".join(text.split()))
    return normalized_pages


def _build_report_digest_input(
    pdf_bytes: bytes,
    *,
    report_id: str,
    generated_at: str,
    scores: Dict[str, int],
    total_score: int,
    logic_version: str,
) -> Dict[str, Any]:
    """Return only data a cumulative verifier can rebuild from PDF and QR."""
    text_extraction_started_at = time.perf_counter()
    pdf_page_text = _extract_pdf_digest_text(pdf_bytes)
    LOGGER.info("EN_TIMING stage=pdf_text_extraction seconds=%.3f", time.perf_counter() - text_extraction_started_at)
    return _normalize_digest_value(
        {
            "digest_schema_version": QR_DIGEST_SCHEMA_VERSION,
            "report_id": report_id,
            "generated_at": generated_at,
            "language": "en",
            "total_score": total_score,
            "dimension_scores": scores,
            "logic_version": logic_version,
            "pdf_page_text": pdf_page_text,
        }
    )


def _find_output_classification(*sources: Dict[str, Any]) -> Any:
    preferred_keys = (
        "output_classification",
        "artifact_classification",
        "classification",
        "classification_label",
        "output_category",
    )

    def walk(value: Any) -> Any:
        if isinstance(value, dict):
            for key in preferred_keys:
                if key in value and value[key] not in (None, "", [], {}):
                    return value[key]
            for child in value.values():
                found = walk(child)
                if found is not None:
                    return found
        elif isinstance(value, (list, tuple)):
            for child in value:
                found = walk(child)
                if found is not None:
                    return found
        return None

    for source in sources:
        found = walk(source)
        if found is not None:
            return found
    return None


def _build_qr_payload(
    pdf_bytes: bytes,
    analysis_data: Dict[str, Any],
    report_data: Dict[str, Any],
    qr_signing_secret: str,
    *,
    language: str = "en",
) -> Dict[str, Any]:
    qr_payload_started_at = time.perf_counter()
    now = datetime.now(timezone.utc)
    scores = _extract_scores(analysis_data)
    report_id = _first_nonempty_text(
        analysis_data.get("report_id"),
        analysis_data.get("doc_id"),
        report_data.get("report_id"),
    ) or _normalize_report_id("", now)
    generated_at = _first_nonempty_text(
        analysis_data.get("generated_at"),
        report_data.get("generated_at"),
    ) or now.isoformat(timespec="seconds")
    logic_version = QR_LOGIC_VERSION
    total_score = _total_score(analysis_data, scores)
    payload: Dict[str, Any] = {
        "service_id": QR_SERVICE_ID,
        "schema_version": QR_SCHEMA_VERSION,
        "report_id": report_id,
        "generated_at": generated_at,
        "language": language,
        "total_score": total_score,
        "dimension_scores": scores,
        "logic_version": logic_version,
        "digest_schema_version": QR_DIGEST_SCHEMA_VERSION,
        "signature_algorithm": QR_SIGNATURE_ALGORITHM,
        "signature_key_id": QR_SIGNATURE_KEY_ID,
    }
    classification = _find_output_classification(analysis_data, report_data)
    if classification is not None:
        payload["output_classification"] = classification

    digest_input = _build_report_digest_input(
        pdf_bytes,
        report_id=report_id,
        generated_at=generated_at,
        scores=scores,
        total_score=total_score,
        logic_version=logic_version,
    )
    digest_started_at = time.perf_counter()
    digest = hashlib.sha256(_canonical_json(digest_input).encode("utf-8")).hexdigest()
    LOGGER.info("EN_TIMING stage=digest_build seconds=%.3f", time.perf_counter() - digest_started_at)
    payload["digest"] = digest
    secret = str(qr_signing_secret or "").strip()
    if not secret:
        raise RuntimeError("QR signing is not configured.")
    signature_data = _canonical_json(payload).encode("utf-8")
    payload["signature"] = hmac.new(
        secret.encode("utf-8"), signature_data, hashlib.sha256
    ).hexdigest()
    LOGGER.info("EN_TIMING stage=qr_payload_build seconds=%.3f", time.perf_counter() - qr_payload_started_at)
    return payload


def _add_qr_to_last_page(pdf_bytes: bytes, payload: Dict[str, Any]) -> bytes:
    reader = PdfReader(BytesIO(pdf_bytes))
    if not reader.pages:
        raise ValueError("Cannot add the English report QR code to an empty PDF.")
    last_page = reader.pages[-1]
    page_width = float(last_page.mediabox.width)
    page_height = float(last_page.mediabox.height)

    qr_data = _canonical_json(payload)
    qr_image_started_at = time.perf_counter()
    qr = qrcode.QRCode(
        error_correction=qrcode.constants.ERROR_CORRECT_M,
        box_size=8,
        border=4,
    )
    qr.add_data(qr_data)
    qr.make(fit=True)
    qr_image = qr.make_image(fill_color="black", back_color="white").convert("RGB")
    qr_buffer = BytesIO()
    qr_image.save(qr_buffer, format="PNG")
    qr_buffer.seek(0)
    LOGGER.info("EN_TIMING stage=qr_image_generation seconds=%.3f", time.perf_counter() - qr_image_started_at)

    qr_size = 38 * mm
    margin = 18 * mm
    block_right = page_width - 27 * mm
    x = block_right - qr_size - 6 * mm
    is_japanese = str(payload.get("language", "en")) == "ja"
    description_font = "CanonicalMeiryo" if is_japanese else "Helvetica"
    if is_japanese:
        _register_canonical_japanese_fonts()
    description_font_size = 7.6
    description_leading = 8.6
    qr_position_leading = 7.4
    description_width = 220
    description_lines: List[str] = []
    if is_japanese:
        description_lines = [
            "このQRコードには、このPDFがAI Usage Skill Visualizerによって",
            "生成されたことを確認するためのレポート識別・検証情報が含まれます。",
            "対話ログやレポート本文は含まれません。",
        ]
    else:
        current_line = ""
        for word in QR_DESCRIPTION_EN.split():
            candidate = f"{current_line} {word}".strip()
            if current_line and pdfmetrics.stringWidth(candidate, description_font, description_font_size) > description_width:
                description_lines.append(current_line)
                current_line = word
            else:
                current_line = candidate
        if current_line:
            description_lines.append(current_line)
    description_y = margin
    description_gap = 5 * mm
    qr_text_gap = 3 * mm
    y = description_y + len(description_lines) * qr_position_leading + description_gap + qr_text_gap
    # Keep the description width unchanged, but align its right edge with
    # the QR quiet-zone edge and move the whole left-aligned block in parallel.
    qr_white_right = x + qr_size + 12
    # Japanese is deliberately kept at the same three fixed lines.  Some
    # glyph runs are wider than the nominal text box, so account for that
    # visible overhang by moving the unchanged block farther left.
    visible_width = description_width
    if is_japanese:
        visible_width = max(
            visible_width,
            max(pdfmetrics.stringWidth(line, description_font, description_font_size) for line in description_lines),
        )
    panel_x = qr_white_right - visible_width - 12
    overlay_buffer = BytesIO()
    canvas = Canvas(overlay_buffer, pagesize=(page_width, page_height))
    canvas.setFillColor(colors.white)
    canvas.rect(
        x - 12,
        y - 12,
        qr_size + 24,
        qr_size + 24,
        fill=1,
        stroke=0,
    )
    canvas.drawImage(ImageReader(qr_buffer), x, y, width=qr_size, height=qr_size, mask="auto")
    canvas.setFillColor(INK)
    canvas.setFont(description_font, description_font_size)
    text_y = description_y + (len(description_lines) - 1) * description_leading
    for line in description_lines:
        canvas.drawString(panel_x + 12, text_y, line)
        text_y -= description_leading
    canvas.save()
    overlay_buffer.seek(0)

    overlay_page = PdfReader(overlay_buffer).pages[0]
    overlay_started_at = time.perf_counter()
    last_page.merge_page(overlay_page)
    LOGGER.info("EN_TIMING stage=qr_pdf_overlay seconds=%.3f", time.perf_counter() - overlay_started_at)
    writer = PdfWriter()
    for page in reader.pages:
        writer.add_page(page)
    result = BytesIO()
    final_write_started_at = time.perf_counter()
    writer.write(result)
    LOGGER.info("EN_TIMING stage=final_pdf_write seconds=%.3f", time.perf_counter() - final_write_started_at)
    return result.getvalue()


def _generate_english_pdf_with_optional_qr(
    pdf_bytes: bytes,
    analysis_data: Dict[str, Any],
    report_data: Dict[str, Any],
    include_qr: bool,
    qr_signing_secret: str,
    language: str = "en",
) -> bytes:
    pdf_started_at = time.perf_counter()
    if not include_qr:
        return pdf_bytes
    # Probe the same PDF round-trip used for the delivered document before
    # calculating the digest. PdfWriter can normalize text extraction while
    # adding the overlay; using this probe keeps PDF-only recomputation stable.
    qr_started_at = time.perf_counter()
    probe_payload = _build_qr_payload(
        pdf_bytes,
        analysis_data,
        report_data,
        qr_signing_secret,
        language=language,
    )
    digest_source_pdf = _add_qr_to_last_page(pdf_bytes, probe_payload)
    final_pdf = _add_qr_to_last_page(
        pdf_bytes,
        _build_qr_payload(
            digest_source_pdf,
            analysis_data,
            report_data,
            qr_signing_secret,
            language=language,
        ),
    )
    LOGGER.info("EN_TIMING stage=qr_digest_hmac seconds=%.3f", time.perf_counter() - qr_started_at)
    LOGGER.info("EN_TIMING stage=pdf_generation seconds=%.3f", time.perf_counter() - pdf_started_at)
    return final_pdf


def _score_band(score: int) -> str:
    if score >= 90:
        return "advanced"
    if score >= 70:
        return "strong"
    if score >= 50:
        return "developing"
    if score >= 40:
        return "limited"
    if score >= 20:
        return "weak"
    return "insufficient"


def _comment_ratios(total: int) -> Tuple[float, float]:
    evaluation_ratio = max(0.15, min(0.85, total / 500.0))
    return evaluation_ratio, 1.0 - evaluation_ratio


def _normalize_report_id(value: Any, now: datetime) -> str:
    report_id = _first_english(value)
    if report_id and "test" not in report_id.lower():
        return report_id
    return f"EN-{now.strftime('%Y%m%d-%H%M%S')}"


