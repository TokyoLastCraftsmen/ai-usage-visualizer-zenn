def _flowable_height(flowable: Any, width: float) -> float:
    _wrapped_width, height = flowable.wrap(width, 100000)
    space_before = float(flowable.getSpaceBefore()) if hasattr(flowable, "getSpaceBefore") else 0.0
    space_after = float(flowable.getSpaceAfter()) if hasattr(flowable, "getSpaceAfter") else 0.0
    return float(height) + space_before + space_after


def _flowables_height(flowables: Sequence[Any], width: float) -> float:
    return sum(_flowable_height(flowable, width) for flowable in flowables)


def _pack_report_sections(
    sections: Sequence[Dict[str, Any]],
    styles: Dict[str, ParagraphStyle],
    width: float,
    page_height: float,
) -> List[Any]:
    """Pack complete cards into body pages while keeping section context visible.

    Each section is a mapping with ``number``, ``title``, and ``cards``. Optional
    ``keep_together_if_fits`` keeps a compact final section on one page when it
    fits on a fresh page. ``start_on_new_page`` preserves an intentional chapter
    boundary. A card may split across as many pages as its complete translated
    text requires; content is never shortened to satisfy a page or card limit.
    """
    # SimpleDocTemplate frames have internal padding, and ReportLab can add a
    # few points around complex nested tables. Keep a conservative reserve so
    # it never performs an unplanned page break after our section header.
    safety_margin = 60.0
    capacity = max(1.0, page_height - safety_margin)
    card_gap = 4 * mm
    section_gap = 4 * mm
    pages: List[List[Any]] = []
    current: List[Any] = []
    used = 0.0

    def flush_page() -> None:
        nonlocal current, used
        if current:
            pages.append(current)
        current = []
        used = 0.0

    def header_flowables(number: str, title: str, continued: bool = False) -> List[Any]:
        display_title = f"{title} - Continued" if continued else title
        return _section_header(number, display_title, styles)

    for section in sections:
        cards = [card for card in section.get("cards", []) if card is not None]
        if not cards:
            continue
        number = str(section.get("number") or "").strip()
        title = str(section.get("title") or "").strip()
        first_header = header_flowables(number, title)
        first_header_height = _flowables_height(first_header, width)
        first_card_height = _flowable_height(cards[0], width)
        whole_section_height = first_header_height + sum(
            _flowable_height(card, width) for card in cards
        ) + card_gap * max(0, len(cards) - 1)

        if current and section.get("start_on_new_page"):
            flush_page()

        if current:
            required = section_gap + first_header_height + first_card_height
            keep_whole = bool(section.get("keep_together_if_fits")) and whole_section_height <= capacity
            if required > capacity - used or (keep_whole and whole_section_height + section_gap > capacity - used):
                flush_page()

        if current:
            current.append(Spacer(1, section_gap))
            used += section_gap
        current.extend(first_header)
        used += first_header_height

        for card_index, card in enumerate(cards):
            card_height = _flowable_height(card, width)
            gap = card_gap if card_index else 0.0
            oversized_for_fresh_page = card_height > capacity - first_header_height
            if card_height + gap > capacity - used and not (
                card_index == 0 and oversized_for_fresh_page
            ):
                flush_page()
                continued_header = header_flowables(number, title, continued=True)
                current.extend(continued_header)
                used += _flowables_height(continued_header, width)
                gap = 0.0
            if gap:
                current.append(Spacer(1, gap))
                used += gap
            current.append(card)
            used += card_height

    flush_page()
    story: List[Any] = []
    for page in pages:
        story.append(PageBreak())
        story.extend(page)
    return story


def _layout_card_from_spec(
    spec: Dict[str, Any],
    styles: Dict[str, ParagraphStyle],
    width: float,
) -> Table:
    """Build a card from content data without embedding report-specific wording."""
    content: List[Any] = []
    table_rows = spec.get("table_rows")
    table_first = bool(spec.get("table_first", True))

    def append_table() -> None:
        if not table_rows:
            return
        rows: List[Tuple[str, str]] = []
        for row in table_rows:
            if isinstance(row, dict):
                rows.append((str(row.get("label") or ""), str(row.get("value") or "")))
            elif isinstance(row, (list, tuple)) and len(row) >= 2:
                rows.append((str(row[0]), str(row[1])))
        if rows:
            content.append(_key_value_table(rows, styles, width - 18))

    if table_first:
        append_table()
        if table_rows and (spec.get("body") or spec.get("bullets")):
            content.append(Spacer(1, 3 * mm))
    body = str(spec.get("body") or "").strip()
    if body:
        content.append(Paragraph(_paragraph_text(body), styles["compact"]))
    bullets = spec.get("bullets") or []
    if bullets:
        if body:
            content.append(Spacer(1, 2.5 * mm))
        content.append(
            Paragraph(
                "<br/><br/>".join(f"- {escape(str(item))}" for item in bullets),
                styles["compact"],
            )
        )
    if not table_first:
        if table_rows and content:
            content.append(Spacer(1, 3 * mm))
        append_table()
    score = str(spec.get("score") or "").strip()
    title = str(spec.get("title") or "").strip()
    if score:
        return _scored_content_card(title, score, content, styles, width)
    return _full_width_card(title, content, styles, width)


