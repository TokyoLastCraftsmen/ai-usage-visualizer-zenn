def _register_canonical_japanese_fonts() -> None:
    if "CanonicalMeiryo" in pdfmetrics.getRegisteredFontNames():
        return
    windows_regular = Path(r"C:\Windows\Fonts\meiryo.ttc")
    windows_bold = Path(r"C:\Windows\Fonts\meiryob.ttc")
    linux_ttf = Path("/usr/share/fonts/opentype/ipaexfont-gothic/ipaexg.ttf")
    if windows_regular.is_file() and windows_bold.is_file():
        # Preserve the existing Windows production font path.
        regular_path, bold_path = windows_regular, windows_bold
    elif linux_ttf.is_file():
        # IPAex Gothic is a standalone TrueType-outline .ttf. Do not add
        # TTC/CFF candidates here: ReportLab TTFont cannot parse those files.
        regular_path = bold_path = linux_ttf
    else:
        regular_path = bold_path = None
    if regular_path is None or bold_path is None:
        raise FileNotFoundError(
            "Japanese PDF font was not found: "
            + ", ".join(str(path) for path in (windows_regular, windows_bold, linux_ttf))
        )
    pdfmetrics.registerFont(
        TTFont("CanonicalMeiryo", str(regular_path))
    )
    pdfmetrics.registerFont(
        TTFont("CanonicalMeiryo-Bold", str(bold_path))
    )


