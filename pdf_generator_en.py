def generate_report_from_canonical_payload(
    analysis_data: Dict[str, Any],
    payload: Dict[str, str],
    *,
    language: str,
) -> bytes:
    """Render canonical report content with the shared English/Japanese layout."""
    if language not in {"en", "ja"}:
        raise ValueError(f"Unsupported canonical PDF language: {language}")
    if language == "ja":
        _register_canonical_japanese_fonts()
        report_title = "AI活用能力評価レポート"
        subject = "日本語完成payloadを使用したローカル多言語版レポート"
        page_callback = _draw_canonical_japanese_page
    else:
        _register_canonical_english_fonts()
        report_title = REPORT_TITLE
        subject = "English translation of the Japanese production AI usage report"
        page_callback = _draw_canonical_english_page
    buffer = BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=27 * mm,
        leftMargin=62 * mm,
        topMargin=24 * mm,
        bottomMargin=20 * mm,
        title=report_title,
        author=APP_NAME,
        subject=subject,
    )
    story = _canonical_payload_story(
        analysis_data or {},
        payload or {},
        document.height,
        language=language,
    )
    document.build(
        story,
        onFirstPage=page_callback,
        onLaterPages=page_callback,
    )
    return buffer.getvalue()


def generate_report_en_from_translated_payload(
    analysis_data: Dict[str, Any],
    translated_payload: Dict[str, str],
    *,
    include_qr: bool = False,
    qr_signing_secret: str = "",
) -> bytes:
    """Render a validated English translation of the Japanese production payload."""
    canonical_render_started_at = time.perf_counter()
    pdf_bytes = generate_report_from_canonical_payload(
        analysis_data,
        translated_payload,
        language="en",
    )
    LOGGER.info("EN_TIMING stage=canonical_pdf_render seconds=%.3f", time.perf_counter() - canonical_render_started_at)
    return _generate_english_pdf_with_optional_qr(
        pdf_bytes, analysis_data or {}, translated_payload or {}, include_qr,
        qr_signing_secret, language="en",
    )


