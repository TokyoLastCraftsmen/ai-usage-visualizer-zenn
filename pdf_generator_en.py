def generate_public_sample_en_report(
    analysis_data: Dict[str, Any],
    cover_data: Dict[str, Any],
    section_specs: Sequence[Dict[str, Any]],
) -> bytes:
    """Generate a public sample using the same dynamic body layout as production."""
    buffer = BytesIO()
    document = SimpleDocTemplate(
        buffer,
        pagesize=A4,
        rightMargin=18 * mm,
        leftMargin=22 * mm,
        topMargin=19 * mm,
        bottomMargin=18 * mm,
        title=REPORT_TITLE,
        author=APP_NAME,
        subject="Public English sample report",
    )
    styles = _build_styles()
    sections: List[Dict[str, Any]] = []
    for section in section_specs:
        sections.append(
            {
                "number": section.get("number"),
                "title": section.get("title"),
                "keep_together_if_fits": section.get("keep_together_if_fits", False),
                "start_on_new_page": section.get("start_on_new_page", False),
                "cards": [
                    _layout_card_from_spec(card_spec, styles, document.width)
                    for card_spec in section.get("cards", [])
                ],
            }
        )
    story = _public_sample_cover_story(analysis_data or {}, cover_data or {}, styles, document.width)
    story.extend(_pack_report_sections(sections, styles, document.width, document.height))
    document.build(story, onFirstPage=_draw_page, onLaterPages=_draw_page)
    return buffer.getvalue()


