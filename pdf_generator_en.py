def _translated_axis_parts(text: str) -> Dict[str, str]:
    labels = (
        ("Evaluation", "evaluation"),
        ("Relationship to the output", "relationship"),
        ("Conclusion", "conclusion"),
    )
    normalized = str(text or "").replace("\r\n", "\n").replace("\r", "\n").strip()
    positions: List[Tuple[int, str, str]] = []
    for label, key in labels:
        match = re.search(
            rf"(?im)^\s*(?:[#*\-]+\s*)?(?:[123][.)]?\s*)?{re.escape(label)}\s*:?\s*$",
            normalized,
        )
        if not match:
            raise ValueError(f"Translated report section is missing: {label}")
        positions.append((match.start(), match.end(), key))
    positions.sort()
    parts: Dict[str, str] = {}
    for index, (_start, content_start, key) in enumerate(positions):
        content_end = positions[index + 1][0] if index + 1 < len(positions) else len(normalized)
        value = normalized[content_start:content_end].strip()
        if not value:
            raise ValueError(f"Translated report section is empty: {key}")
        parts[key] = value
    return parts


