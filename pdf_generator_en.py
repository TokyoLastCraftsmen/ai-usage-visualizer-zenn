def _normalize_japanese_display_value(value: Any) -> Any:
    """Normalize Japanese PDF display wording without changing source data."""
    if isinstance(value, str):
        normalized = value
        for old, new in _JAPANESE_OUTPUT_DISPLAY_REPLACEMENTS:
            normalized = normalized.replace(old, new)
        return normalized
    if isinstance(value, list):
        return [_normalize_japanese_display_value(item) for item in value]
    if isinstance(value, tuple):
        return tuple(_normalize_japanese_display_value(item) for item in value)
    if isinstance(value, dict):
        return {
            key: _normalize_japanese_display_value(item)
            for key, item in value.items()
        }
    return value


