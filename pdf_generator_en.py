def _canonical_japanese_practical_level(total: int) -> str:
    average = round(total / 5)
    if average >= 90:
        return "高度な実務活用レベル"
    if average >= 70:
        return "安定した実務活用レベル"
    if average >= 50:
        return "発展途上の実務活用レベル"
    if average >= 40:
        return "限定的な実務活用レベル"
    if average >= 20:
        return "実務活用が弱いレベル"
    return "実務活用レベルを確認できません"


