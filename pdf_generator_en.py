def _pack_canonical_english_sections(
    sections: Sequence[Dict[str, Any]],
    styles: Dict[str, ParagraphStyle],
    page_height: float,
    *,
    continued_label: str = "Continued",
) -> List[Any]:
    # SimpleDocTemplate frames reserve 6 pt at the top and bottom. Keep only
    # that real frame reserve so complete cards are not pushed to extra pages.
    safety_margin = 12.0
    capacity = max(1.0, page_height - safety_margin)
    card_gap = 4 * mm
    pages: List[List[Any]] = []

    for section in sections:
        cards = [card for card in section.get("cards", []) if card is not None]
        if not cards:
            continue
        number = str(section.get("number") or "").strip()
        title = str(section.get("title") or "").strip()
        minimum_lines = max(1, int(section.get("header_minimum_lines") or 1))
        current = _canonical_section_header(
            number,
            title,
            styles,
            continued_label=continued_label,
            minimum_lines=minimum_lines,
        )
        used = _flowables_height(current, CANONICAL_CONTENT_WIDTH)
        for card_index, card in enumerate(cards):
            card_height = _flowable_height(card, CANONICAL_CONTENT_WIDTH)
            gap = card_gap if card_index else 0.0
            force_new_page = bool(section.get("separate_cards")) and card_index > 0
            if force_new_page or (card_height + gap > capacity - used and card_height <= capacity):
                pages.append(current)
                current = _canonical_section_header(
                    number,
                    title,
                    styles,
                    continued=True,
                    continued_label=continued_label,
                    minimum_lines=minimum_lines,
                )
                used = _flowables_height(current, CANONICAL_CONTENT_WIDTH)
                gap = 0.0
            if gap:
                current.append(Spacer(1, gap))
                used += gap
            current.append(card)
            used += card_height
        pages.append(current)

    story: List[Any] = []
    for page in pages:
        story.append(PageBreak())
        story.extend(page)
    return story


